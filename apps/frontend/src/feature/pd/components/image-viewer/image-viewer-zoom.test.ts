import { describe, expect, it } from "vitest";
import {
  ZOOM_MAX,
  ZOOM_MIN,
  ホイールで変わる倍率を求める,
  ボタンで変わる倍率を求める,
  指した点を保つ送り位置を求める,
  画像を枠に収める大きさを求める,
} from "./image-viewer-zoom";

describe("画像を枠に収める大きさを求める", () => {
  it("枠より大きい横長の画像は横幅を枠に合わせて縦横比を保つ", () => {
    const size = 画像を枠に収める大きさを求める({
      画像: { 幅: 2000, 高さ: 1000 },
      枠: { 幅: 800, 高さ: 600 },
    });

    expect(size).toEqual({ 幅: 800, 高さ: 400 });
  });

  it("枠より大きい縦長の画像は高さを枠に合わせて縦横比を保つ", () => {
    const size = 画像を枠に収める大きさを求める({
      画像: { 幅: 1000, 高さ: 3000 },
      枠: { 幅: 800, 高さ: 600 },
    });

    expect(size).toEqual({ 幅: 200, 高さ: 600 });
  });

  it("枠より小さい画像は引き伸ばさず元の大きさで出す", () => {
    const size = 画像を枠に収める大きさを求める({
      画像: { 幅: 300, 高さ: 200 },
      枠: { 幅: 800, 高さ: 600 },
    });

    expect(size).toEqual({ 幅: 300, 高さ: 200 });
  });

  it("大きさが分からない画像は大きさ 0 として扱う", () => {
    const size = 画像を枠に収める大きさを求める({
      画像: { 幅: 0, 高さ: 0 },
      枠: { 幅: 800, 高さ: 600 },
    });

    expect(size).toEqual({ 幅: 0, 高さ: 0 });
  });
});

describe("ホイールで変わる倍率を求める", () => {
  it("奥へ回すと拡大する", () => {
    const next = ホイールで変わる倍率を求める({
      倍率: 2,
      送り量: -100,
      送りの単位: 0,
    });

    expect(next).toBeGreaterThan(2);
  });

  it("手前へ回すと縮小する", () => {
    const next = ホイールで変わる倍率を求める({
      倍率: 2,
      送り量: 100,
      送りの単位: 0,
    });

    expect(next).toBeLessThan(2);
  });

  it("行単位の送りは画素単位の同じ量より大きく倍率を変える", () => {
    const byLine = ホイールで変わる倍率を求める({
      倍率: 2,
      送り量: -3,
      送りの単位: 1,
    });
    const byPixel = ホイールで変わる倍率を求める({
      倍率: 2,
      送り量: -3,
      送りの単位: 0,
    });

    expect(byLine).toBeGreaterThan(byPixel);
  });

  it("どれだけ縮小しても枠に収まる大きさより小さくしない", () => {
    const next = ホイールで変わる倍率を求める({
      倍率: ZOOM_MIN,
      送り量: 10000,
      送りの単位: 0,
    });

    expect(next).toBe(ZOOM_MIN);
  });

  it("どれだけ拡大しても上限を超えない", () => {
    const next = ホイールで変わる倍率を求める({
      倍率: ZOOM_MAX,
      送り量: -10000,
      送りの単位: 0,
    });

    expect(next).toBe(ZOOM_MAX);
  });
});

describe("ボタンで変わる倍率を求める", () => {
  it("拡大ボタンは一段大きくする", () => {
    const next = ボタンで変わる倍率を求める({ 倍率: 1, 向き: "拡大" });

    expect(next).toBeGreaterThan(1);
  });

  it("縮小ボタンは一段小さくする", () => {
    const next = ボタンで変わる倍率を求める({ 倍率: 2, 向き: "縮小" });

    expect(next).toBeLessThan(2);
  });

  it("上限の近くで拡大すると上限で止まる", () => {
    const next = ボタンで変わる倍率を求める({
      倍率: ZOOM_MAX - 0.1,
      向き: "拡大",
    });

    expect(next).toBe(ZOOM_MAX);
  });

  it("下限の近くで縮小すると下限で止まる", () => {
    const next = ボタンで変わる倍率を求める({
      倍率: ZOOM_MIN + 0.1,
      向き: "縮小",
    });

    expect(next).toBe(ZOOM_MIN);
  });
});

describe("指した点を保つ送り位置を求める", () => {
  it("枠からはみ出した画像を 2 倍にすると指した点が同じ場所に残る", () => {
    const next = 指した点を保つ送り位置を求める({
      送り位置: 100,
      指した位置: 200,
      枠の長さ: 800,
      前の中身の長さ: 1600,
      次の中身の長さ: 3200,
    });

    expect(next).toBe(400);
  });

  it("枠の中央に収まっていた画像を拡大すると中央寄せの余白を差し引いて指した点を保つ", () => {
    const next = 指した点を保つ送り位置を求める({
      送り位置: 0,
      指した位置: 400,
      枠の長さ: 800,
      前の中身の長さ: 400,
      次の中身の長さ: 1600,
    });

    expect(next).toBe(400);
  });

  it("縮小して画像が枠に収まったら送り位置を先頭に戻す", () => {
    const next = 指した点を保つ送り位置を求める({
      送り位置: 500,
      指した位置: 100,
      枠の長さ: 800,
      前の中身の長さ: 1600,
      次の中身の長さ: 600,
    });

    expect(next).toBe(0);
  });

  it("端を指して拡大しても送り位置は送れる範囲を超えない", () => {
    const next = 指した点を保つ送り位置を求める({
      送り位置: 800,
      指した位置: 800,
      枠の長さ: 800,
      前の中身の長さ: 1600,
      次の中身の長さ: 2000,
    });

    expect(next).toBe(1200);
  });
});
